package Pertemuan15;

public class TugasNilai {
    TugasMahasiswa mahasiswa;
    TugasMataKuliah mataKuliah;
    double nilai;

    public TugasNilai(TugasMahasiswa mahasiswa, TugasMataKuliah mataKuliah, double nilai) {
        this.mahasiswa = mahasiswa;
        this.mataKuliah = mataKuliah;
        this.nilai = nilai;
    }
}