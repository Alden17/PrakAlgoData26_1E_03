package Minggu5;

public class Nilai {

    String namaMahasiswa;
    String nomorInduk;
    int angkatan;
    int uts;
    int uas;

    public Nilai(String namaMahasiswa, String nomorInduk, int angkatan, int uts, int uas) {
        this.namaMahasiswa = namaMahasiswa;
        this.nomorInduk = nomorInduk;
        this.angkatan = angkatan;
        this.uts = uts;
        this.uas = uas;
    }
}   
